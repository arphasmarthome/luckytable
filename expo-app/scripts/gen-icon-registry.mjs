// Scans src/ for icon names (Icon name="…", icon="…", iconRight="…", icon: "…") and writes a registry that
// imports only those lucide icons, so the web bundle does not ship all ~1,800 glyphs.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = path.join(root, "src");
const names = new Set(["circle"]);
const patterns = [/\bname=\{?"([a-z0-9-]+)"/g, /\bicon(?:Right)?=\{?"([a-z0-9-]+)"/g, /\bicon(?:Right)?:\s*"([a-z0-9-]+)"/g, /\bicon\(\s*"([a-z0-9-]+)"/g, /\biconComponent\(\s*"([a-z0-9-]+)"/g, /\?\s*"([a-z0-9-]+)"\s*:\s*"([a-z0-9-]+)"/g];
function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full);
    else if (/\.(tsx?|jsx?)$/.test(entry.name) && !entry.name.endsWith("icon-registry.ts")) {
      const text = fs.readFileSync(full, "utf8");
      for (const pattern of patterns) for (const match of text.matchAll(pattern)) for (const name of match.slice(1)) if (name) names.add(name);
    }
  }
}
walk(src);
const pascal = (name) => name.split("-").map((part) => (part ? part[0].toUpperCase() + part.slice(1) : "")).join("");
const iconsDir = path.join(root, "node_modules", "lucide-react-native", "dist", "esm", "icons");
const known = [...names].filter((name) => fs.existsSync(path.join(iconsDir, `${name}.mjs`))).sort();
const unknown = [...names].filter((name) => !fs.existsSync(path.join(iconsDir, `${name}.mjs`))).sort();
const out = `/* Generated by scripts/gen-icon-registry.mjs — run \`node scripts/gen-icon-registry.mjs\` after adding icons. */
import type { LucideIcon } from "lucide-react-native";
${known.map((name) => `import ${pascal(name)} from "lucide-react-native/icons/${name}";`).join("\n")}

export const ICONS: Record<string, LucideIcon> = {
${known.map((name) => `  "${name}": ${pascal(name)},`).join("\n")}
};
`;
fs.writeFileSync(path.join(src, "components", "ui", "icon-registry.ts"), out);
console.log(`icon registry: ${known.length} icons`);
if (unknown.length) console.log("not lucide icons (ignored):", unknown.join(", "));
